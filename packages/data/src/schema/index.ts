/* ============================================================
 * USERS
 * ============================================================ */

export const Table__User = mysqlTable(
  "user",
  {
    id: autogeneratedId(),
    name: varchar("name", { length: 255 }).notNull(),
    employeeId: char("employee_id", { length: 12 }).notNull().unique(),
    email: varchar("email", { length: 255 }).notNull().unique(),
    password: varchar("password", { length: 255 }).notNull(),
    phoneNumber: phoneNumberColumn("phone_number"),
    emergencyPhoneNumber: char("emergency_phone_number", { length: 10 }),
    location: varchar("location", { length: 255 }).notNull(),
    pin: char("pin", { length: 6 }).notNull(),
    role: roleEnum()
      .$defaultFn(() => "AGENT")
      .notNull(),
    referrerEmployeeId: char("referrer_id", { length: 12 }),

    ...metadata("USER"),
  },
  (t) => [
    foreignKey({
      columns: [t.referrerEmployeeId],
      foreignColumns: [t.employeeId],
      name: "user_referrer_id_fk",
    })
      .onDelete("set null")
      .onUpdate("cascade"),
  ],
);

